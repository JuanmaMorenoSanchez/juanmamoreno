// Rewrites the bundled records from the live ones, before every build.
//
// An artwork page must carry its own provenance in the html: the pages are
// prerendered and read without javascript, and where a painting has been shown
// is the kind of fact a reader comes for. So the api's answer is written down
// here at build time and corrected from the api a moment later in the browser.
//
// A build that cannot reach the api keeps the file that is already there,
// rather than writing an empty one and stripping the provenance off every page:
// records a week old are worth having. An empty list that the api actually
// answered with is a different thing and is written down as true, because at
// the time of writing no painting has a record yet.
import { readFile, writeFile } from 'node:fs/promises';

const target = 'src/app/domain/artwork/record-fallback.constants.ts';
const environmentFile = 'src/environments/environment.prod.ts';

const render = (records) => `// Generated by scripts/generate-record-fallback.mjs. Do not edit.
//
// What had happened to each painting when this build was made, so an artwork
// page carries its own record without javascript.
import { ArtworkRecord } from './record.entity';

export const RECORDS_AT_LAST_BUILD: readonly ArtworkRecord[] = ${JSON.stringify(records, null, 2)};
`;

try {
  const environment = await readFile(environmentFile, 'utf8');
  const backendUrl = environment.match(/backendUrl:\s*'([^']+)'/)?.[1];
  if (!backendUrl) {
    throw new Error(`no backendUrl found in ${environmentFile}`);
  }

  const response = await fetch(`${backendUrl}artwork-record`);
  if (!response.ok) {
    throw new Error(`the records answered ${response.status}`);
  }

  const answer = await response.json();
  const records = answer?.data?.records;
  if (!Array.isArray(records)) {
    throw new Error('the records came back as something other than a list');
  }

  await writeFile(target, render(records), 'utf8');
  const lines = records.reduce((count, one) => count + (one.entries?.length ?? 0), 0);
  console.log(`generate-record-fallback: ${records.length} records, ${lines} lines -> ${target}`);
} catch (failure) {
  console.warn(`generate-record-fallback: keeping the bundled records — ${failure.message}`);
}
