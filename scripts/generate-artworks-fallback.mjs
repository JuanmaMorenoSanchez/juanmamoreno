// Rewrites the bundled catalogue from the live one, before every build.
//
// A reader arriving for the first time on an artwork page has no transferred
// catalogue — only /artworks carries one, since 430kB on all 386 pages would
// be a bad trade — and nothing in localStorage yet, so the app paints this
// file while the API answers. Maintained by hand it drifted: an artwork added
// to the collection stayed missing from that first paint until somebody
// remembered to regenerate it. Running here means it cannot fall behind.
//
// Only the fields the app reads are kept. The snapshot is ~430kB and most of
// it is chain metadata no page ever looks at.
//
// A build with no network keeps the file that is already there: a stale
// catalogue is worth having, an empty one is not.
import { readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';

const target = 'src/app/features/artwork/constants/artworks-fallback.constants.ts';
const environmentFile = 'src/environments/environment.prod.ts';

const slim = (nft) => ({
  tokenId: nft.tokenId,
  name: nft.name,
  image: {
    originalUrl: nft.image?.originalUrl,
    cachedUrl: nft.image?.cachedUrl,
    thumbnailUrl: nft.image?.thumbnailUrl,
    pngUrl: nft.image?.pngUrl,
  },
  raw: { metadata: { attributes: nft.raw?.metadata?.attributes ?? [] } },
});

// JSON.stringify drops undefined keys, which is what an artwork missing one of
// the image urls should produce rather than an explicit undefined.
const render = (artworks) => `// Generated by scripts/generate-artworks-fallback.mjs. Do not edit.
//
// Slimmed copy of the nfts-snapshot endpoint: the fields the app reads, so a
// first-time reader sees the catalogue before the API answers.
import { Nft } from '@domain/artwork/artwork.entity';
import { ApiResponse } from '@shared/types/api-response.type';

export const FALLBACK_ARTWORKS_API_CALL: ApiResponse<Nft[]> = ${JSON.stringify(
  { success: true, data: artworks },
  null,
  2
)};
`;

try {
  const environment = await readFile(environmentFile, 'utf8');
  const backendUrl = environment.match(/backendUrl:\s*'([^']+)'/)?.[1];
  if (!backendUrl) {
    throw new Error(`no backendUrl found in ${environmentFile}`);
  }

  const response = await fetch(`${backendUrl}nfts-snapshot`);
  if (!response.ok) {
    throw new Error(`the catalogue answered ${response.status}`);
  }

  const { data } = await response.json();
  if (!Array.isArray(data) || !data.length) {
    throw new Error('the catalogue came back empty');
  }

  const current = await readFile(target, 'utf8').catch(() => '');

  await writeFile(target, render(data.map(slim)), 'utf8');
  // Written as JSON, so it needs the repo's formatting before anyone reads or
  // commits it. Comparing before formatting would never match what is on disk,
  // and every build would report a change it had not made.
  execFileSync('npx', ['prettier', '--write', target], { stdio: 'ignore', shell: true });

  const updated = await readFile(target, 'utf8');
  console.log(
    updated === current
      ? `fallback: ${data.length} artworks, unchanged`
      : `fallback: ${target} -> ${data.length} artworks`
  );
} catch (error) {
  console.warn(`fallback: keeping the bundled catalogue as it is (${error.message})`);
}
