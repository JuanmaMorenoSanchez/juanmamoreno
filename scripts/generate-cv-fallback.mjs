// Rewrites the bundled cv from the live one, before every build.
//
// The cv page must be a complete page in the html before any request is sent:
// it is prerendered, it is read without javascript, and a career is the one
// thing on it. So the api's answer is written down here at build time and
// corrected from the api a moment later in the browser.
//
// Maintained by hand this would drift, which is exactly what it replaces — the
// cv used to be an array in the source, and the whole point of moving it was
// that adding a show should not need a commit. Running here means the bundled
// copy cannot fall behind by more than one deploy.
//
// A build with no network keeps the file that is already there: a cv a week
// old is worth having, an empty one is not.
import { readFile, writeFile } from 'node:fs/promises';

const target = 'src/app/domain/cv/cv-fallback.constants.ts';
const environmentFile = 'src/environments/environment.prod.ts';

/** The fields the app reads, in the order the entity declares them. */
const slim = (entry) => ({
  id: entry.id,
  kind: entry.kind,
  year: entry.year,
  ...(entry.month !== undefined ? { month: entry.month } : {}),
  title: entry.title,
  ...(entry.venue ? { venue: entry.venue } : {}),
  ...(entry.city ? { city: entry.city } : {}),
  country: entry.country,
  ...(entry.titleUrl ? { titleUrl: entry.titleUrl } : {}),
  ...(entry.venueUrl ? { venueUrl: entry.venueUrl } : {}),
});

const render = (entries) => `// Generated by scripts/generate-cv-fallback.mjs. Do not edit.
//
// The cv as the api served it when this build was made, so the prerendered
// page carries the whole career without javascript and a first-time reader
// sees it before any request returns.
import { CvEntry } from './cv-entry.entity';

export const CV_AT_LAST_BUILD: readonly CvEntry[] = ${JSON.stringify(entries, null, 2)};
`;

try {
  const environment = await readFile(environmentFile, 'utf8');
  const backendUrl = environment.match(/backendUrl:\s*'([^']+)'/)?.[1];
  if (!backendUrl) {
    throw new Error(`no backendUrl found in ${environmentFile}`);
  }

  const response = await fetch(`${backendUrl}cv/entries`);
  if (!response.ok) {
    throw new Error(`the cv answered ${response.status}`);
  }

  const answer = await response.json();
  const entries = answer?.data?.entries;
  if (!Array.isArray(entries) || !entries.length) {
    throw new Error('the cv came back with no entries in it');
  }

  await writeFile(target, render(entries.map(slim)), 'utf8');
  console.log(`generate-cv-fallback: ${entries.length} entries written to ${target}`);
} catch (failure) {
  console.warn(`generate-cv-fallback: keeping the bundled cv — ${failure.message}`);
}
