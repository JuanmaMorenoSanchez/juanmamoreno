"""
Would Instagram take this clip?

The one question that cannot be answered by publishing, because publishing is
the thing being avoided: a reel goes out under his name and there is no draft
an API can write to. So the clip is measured against Meta's published
specification instead, clause by clause, with `ffprobe` — the same tool a
player uses to decide whether it can open the file.

Every number here is quoted from Meta's content-publishing documentation for a
REELS container, and each one is checked against a file this engine actually
produced rather than against the arguments it meant to pass to ffmpeg. The
difference matters: `-pix_fmt yuv420p` on the command line proves nothing if a
later filter changes it back.

The clip is made here, from frames, rather than generated by the model. The
model takes twenty minutes and decides what the picture *is*; the encoder
decides what the file *is*, and only the second is in question.
"""

import json
import subprocess
import unittest
from pathlib import Path
from tempfile import TemporaryDirectory

import numpy as np

from engine import video

#: Meta's REELS specification, as documented, in the units it uses.
LEAST_SECONDS = 3
MOST_SECONDS = 15 * 60
MOST_BYTES = 300 * 1024 * 1024
SLOWEST_FPS = 23
FASTEST_FPS = 60
WIDEST = 10.0
NARROWEST = 0.01


def probe(where: Path) -> dict:
    """What ffprobe says about a file, as the player would see it."""
    binary = Path(video.ffmpeg())
    ran = subprocess.run(
        [
            str(binary.with_name("ffprobe" + binary.suffix)),
            "-v", "error",
            "-show_streams",
            "-show_format",
            "-of", "json",
            str(where),
        ],
        capture_output=True,
        text=True,
    )
    assert ran.returncode == 0, ran.stderr
    return json.loads(ran.stdout)


def a_clip(folder: str, seconds: float = 3.0, size: tuple[int, int] = (768, 832)) -> Path:
    """A real file out of the real encoder, of about the right length."""
    wide, high = size
    count = video.frames_for(seconds)
    rng = np.random.default_rng(4)
    # Noisy rather than flat, so the encoder does real work and the bitrate is
    # not an artefact of encoding a blank wall.
    base = rng.integers(30, 200, size=(high, wide, 3), dtype=np.uint8)
    frames = [np.roll(base, i * 3, axis=1) for i in range(count)]
    return video.write_video(frames, Path(folder) / "clip.mp4", fps=video.FPS)


class ClipMeetsInstagramTest(unittest.TestCase):
    """One test per clause, so a failure names the clause that broke."""

    @classmethod
    def setUpClass(cls) -> None:
        try:
            video.ffmpeg()
        except FileNotFoundError as why:  # pragma: no cover - a fact about the machine
            raise unittest.SkipTest(str(why))

        cls._folder = TemporaryDirectory()
        cls.where = a_clip(cls._folder.name)
        cls.said = probe(cls.where)
        cls.video = next(s for s in cls.said["streams"] if s["codec_type"] == "video")
        cls.audio = [s for s in cls.said["streams"] if s["codec_type"] == "audio"]

    @classmethod
    def tearDownClass(cls) -> None:
        cls._folder.cleanup()

    # ---- the container ----

    def test_it_is_an_mp4(self) -> None:
        self.assertIn("mp4", self.said["format"]["format_name"])

    def test_the_index_is_at_the_front_of_the_file(self) -> None:
        """`moov` before `mdat`, which the spec asks for by name.

        It is what lets a player start before the whole file has arrived. The
        `+faststart` flag is what puts it there, and a flag is a claim — this
        reads the bytes.
        """
        head = self.where.read_bytes()[:4096]
        self.assertIn(b"moov", head, "the index is not at the front of the file")
        if b"mdat" in head:
            self.assertLess(head.index(b"moov"), head.index(b"mdat"))

    def test_it_is_smaller_than_the_ceiling(self) -> None:
        self.assertLess(int(self.said["format"]["size"]), MOST_BYTES)

    # ---- the video stream ----

    def test_the_codec_is_one_of_the_two_allowed(self) -> None:
        self.assertIn(self.video["codec_name"], ("h264", "hevc"))

    def test_the_chroma_is_subsampled_the_way_every_player_expects(self) -> None:
        # Not pedantry: yuv444 plays in ffmpeg and in nothing else.
        self.assertEqual(self.video["pix_fmt"], "yuv420p")

    def test_the_scan_is_progressive(self) -> None:
        self.assertNotEqual(self.video.get("field_order", "progressive"), "tt")

    def test_the_frame_rate_is_inside_the_permitted_range(self) -> None:
        top, bottom = (int(n) for n in self.video["r_frame_rate"].split("/"))
        fps = top / bottom
        self.assertGreaterEqual(fps, SLOWEST_FPS)
        self.assertLessEqual(fps, FASTEST_FPS)

    # ---- the audio stream ----

    def test_there_is_an_audio_stream_at_all(self) -> None:
        """Silent, and present.

        The spec lists audio requirements and never says audio is optional, so
        a video-only file might be refused — and the only way to find out is
        to publish one under his name. Silence costs a few kilobytes and ends
        the question.
        """
        self.assertEqual(len(self.audio), 1, "a reel with no audio stream may be refused")

    def test_the_audio_is_aac_at_the_rate_asked_for(self) -> None:
        sound = self.audio[0]
        self.assertEqual(sound["codec_name"], "aac")
        self.assertLessEqual(int(sound["sample_rate"]), 48_000)
        self.assertIn(int(sound["channels"]), (1, 2))

    # ---- the shape and the length ----

    def test_it_runs_at_least_the_three_seconds_instagram_wants(self) -> None:
        # The clause that is refused at publishing time, after the twenty-odd
        # minutes of generating.
        self.assertGreaterEqual(float(self.said["format"]["duration"]), LEAST_SECONDS)

    def test_it_runs_less_than_the_quarter_of_an_hour_allowed(self) -> None:
        self.assertLess(float(self.said["format"]["duration"]), MOST_SECONDS)

    def test_the_shape_is_inside_the_permitted_range(self) -> None:
        """0.01:1 to 10:1 — which a painting-shaped clip is, comfortably.

        9:16 is only *recommended*, and this engine does not pad to it: a
        clip is the painting's own shape and Instagram letterboxes it. That
        choice is only safe because of this range, so the range is tested.
        """
        ratio = int(self.video["width"]) / int(self.video["height"])
        self.assertGreater(ratio, NARROWEST)
        self.assertLess(ratio, WIDEST)

    def test_the_tallest_painting_is_still_inside_the_range(self) -> None:
        # Asked of `fit` rather than of a made-up pair: the narrowest clip
        # this engine can produce is whatever the tallest painting becomes,
        # and 0.01:1 is a long way from any canvas.
        from PIL import Image

        wide, high = video.fit(Image.new("RGB", (900, 4533)), longest=832)
        self.assertGreater(wide / high, NARROWEST)


class EveryClipThisEngineMakesTest(unittest.TestCase):
    """The same clauses, over the shapes and lengths the node can be set to."""

    @classmethod
    def setUpClass(cls) -> None:
        try:
            video.ffmpeg()
        except FileNotFoundError as why:  # pragma: no cover
            raise unittest.SkipTest(str(why))

    def test_every_setting_the_node_offers_makes_a_publishable_clip(self) -> None:
        # The extremes of the Video node's own limits: shortest and longest,
        # smallest and largest, and the squarest and narrowest a painting
        # becomes after `fit`.
        settings = [
            (3.0, (448, 448)),
            (3.0, (832, 448)),
            (5.0, (448, 832)),
        ]
        with TemporaryDirectory() as folder:
            for seconds, size in settings:
                with self.subTest(seconds=seconds, size=size):
                    where = a_clip(folder, seconds=seconds, size=size)
                    said = probe(where)
                    stream = next(s for s in said["streams"] if s["codec_type"] == "video")
                    ratio = int(stream["width"]) / int(stream["height"])

                    self.assertGreaterEqual(float(said["format"]["duration"]), LEAST_SECONDS)
                    self.assertLess(int(said["format"]["size"]), MOST_BYTES)
                    self.assertEqual(stream["pix_fmt"], "yuv420p")
                    self.assertGreater(ratio, NARROWEST)
                    self.assertLess(ratio, WIDEST)
                    self.assertTrue(
                        any(s["codec_type"] == "audio" for s in said["streams"]),
                        "no audio stream",
                    )


if __name__ == "__main__":
    unittest.main()
